it('no data loaded: a calm state with Add your files, and no report', async () => {
  load({ imports: [], runs: [], tests: [], attempts: [], failures: [] }, 'empty');
  const onBrowse = vi.fn();
  show('scope=all', onBrowse);
  expect(screen.getByText('No results to report yet')).toBeInTheDocument();
  expect(screen.getByText('Add your files, or try the sample data, and the report appears here.')).toBeInTheDocument();
  await userEvent.click(screen.getByRole('button', { name: 'Add your files' }));
  expect(onBrowse).toHaveBeenCalled();
  expect(screen.queryByRole('button', { name: 'Copy Markdown' })).toBeNull();
});

it('a test with a likely cause gets "Likely cause" in the preview and the Markdown; the fake token never appears', async () => {
  const REFUSED = (n: number) => `page.goto: net::ERR_CONNECTION_REFUSED at http://127.0.0.1:${40000 + n}/api/x${n}\nauthorization: Bearer ${FAKE}`;
  const ds = buildGroups(Array.from({ length: 4 }, (_, i): Fail => ({ run: i, test: 'net', message: REFUSED(i), stack: `Error: x\n    at /repo/tests/net.spec.ts:${10 + i}:3` })));
  ds.runs.forEach((r) => ds.attempts.push({ attemptId: `p-${r.runId}`, runId: r.runId, testId: 'net', repeatIndex: 0, retryIndex: 1, status: 'pass', durationMs: 500 }));
  load(ds);
  show('scope=all');
  await waitFor(() => expect(screen.getByRole('article')).toHaveTextContent('Likely cause: Network or external service (high confidence)'));
  await userEvent.click(screen.getByRole('button', { name: 'Download .md' }));
  expect(files[0]!.body).toContain('Likely cause: Network or external service (high confidence)');
  expect(document.body.innerHTML).not.toContain('FAKE-TOKEN');
  expect(files[0]!.body).not.toContain('FAKE-TOKEN');
});

it('a hostile test name is plain text in the preview and escaped in the Markdown', async () => {
  const ds = fixture();
  ds.tests.find((t) => t.testId === 'alpha')!.title = '<img src=x onerror=alert(1)> `x` ## not a heading';
  load(ds);
  show('scope=all');
  expect(document.querySelector('img')).toBeNull();
  await userEvent.click(screen.getByRole('button', { name: 'Download .md' }));
  expect(files[0]!.body).toContain('\\<img src=x onerror=alert(1)\\>');
  expect(files[0]!.body.split('\n').filter((l) => l.startsWith('## '))).toEqual(['## Summary', '## Top Flaky tests']);
});
