// Lab acceptance and detection report (spec sections 11.1 and 17). Node only: reads files from disk.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import process from 'node:process';
import { parsePlaywrightReport } from '../src/engine/import/playwright';
import { addImport, emptyDataset } from '../src/engine/dataset';
import { scoreTests } from '../src/engine/score/score';
import type { Dataset } from '../src/engine/types';

type ManifestEntry = { file: string; commit: string };
type Method = 'engine' | 'baseline';
export interface Metrics {
  tp: number;
  fp: number;
  fn: number;
  precision: number | null;
  recall: number | null;
  f1: number | null;
}
export interface Row extends Metrics {
  method: Method;
  runs: number;
}

const HISTORY_LENGTHS = [4, 8, 12];
const IMPORTED_AT = '2026-11-20T00:00:00.000Z'; // fixed so record IDs are stable between report runs

export function loadLab(files: ManifestEntry[], dir: string): Dataset {
  return files.reduce(
    (ds, { file, commit }, order) =>
      addImport(
        ds,
        parsePlaywrightReport(readFileSync(`${dir}/${file}`, 'utf8'), {
          fileName: file,
          importedAt: IMPORTED_AT,
          order,
          commitLabel: commit,
        }),
      ),
    emptyDataset(),
  );
}

// precision/F1 are null when undefined (nothing predicted, or nothing to find).
export function prf(predicted: Set<string>, truth: Set<string>): Metrics {
  const tp = [...predicted].filter((t) => truth.has(t)).length;
  const fp = predicted.size - tp;
  const fn = truth.size - tp;
  const precision = predicted.size === 0 ? null : tp / predicted.size;
  const recall = truth.size === 0 ? null : tp / truth.size;
  const f1 = precision === null || recall === null || precision + recall === 0 ? null : (2 * precision * recall) / (precision + recall);
  return { tp, fp, fn, precision, recall, f1 };
}

// Baseline: titles Playwright itself marked "flaky" (failed, then passed on retry) in any loaded run.
function playwrightFlaky(files: ManifestEntry[], dir: string): Set<string> {
  const out = new Set<string>();
  type Suite = { suites?: Suite[]; specs?: Array<{ title: string; tests: Array<{ status?: string }> }> };
  const walk = (s: Suite) => {
    for (const spec of s.specs ?? []) if (spec.tests.some((t) => t.status === 'flaky')) out.add(spec.title);
    (s.suites ?? []).forEach(walk);
  };
  for (const { file } of files) (JSON.parse(readFileSync(`${dir}/${file}`, 'utf8')) as Suite).suites?.forEach(walk);
  return out;
}

export function evaluate(manifest: ManifestEntry[], dir: string, labels: Record<string, string>): Row[] {
  const rows: Row[] = [];
  for (const method of ['engine', 'baseline'] as const) {
    for (const runs of HISTORY_LENGTHS) {
      const files = manifest.slice(0, runs);
      const ds = loadLab(files, dir);
      // Only tests present in this much history can be found.
      const truth = new Set(ds.tests.map((t) => t.title).filter((title) => labels[title] === 'flaky'));
      const title = new Map(ds.tests.map((t) => [t.testId, t.title]));
      const predicted =
        method === 'engine'
          ? new Set(scoreTests(ds).filter((s) => s.label === 'flaky').map((s) => title.get(s.testId)!))
          : playwrightFlaky(files, dir);
      rows.push({ method, runs, ...prf(predicted, truth) });
    }
  }
  return rows;
}

const fmt = (x: number | null) => (x === null ? 'n/a' : x.toFixed(2));

export function buildReport(rows: Row[]): string {
  const name = { engine: 'Engine (Flaky label)', baseline: 'Playwright baseline' };
  const metric = (r: Row) => `${r.runs}:${fmt(r.precision)}:${fmt(r.recall)}:${fmt(r.f1)}`;
  const tie = rows.filter((r) => r.method === 'engine').map(metric).join() === rows.filter((r) => r.method === 'baseline').map(metric).join();
  const table = rows.map(
    (r) => `| ${name[r.method]} | ${r.runs} | ${fmt(r.precision)} | ${fmt(r.recall)} | ${fmt(r.f1)} | ${r.tp} | ${r.fp} | ${r.fn} |`,
  );
  return [
    '# Flake lab: detection report',
    '',
    'Generated by `npm run eval:lab` from `fixtures/lab/` and `flake-lab/labels.json`. Do not edit by hand.',
    '',
    '## Method',
    '',
    '- Positive class: tests whose ground-truth label is `flaky` (3 of the 9 lab tests).',
    '- History length N: the first N runs in `fixtures/lab/manifest.json` order (2 runs per commit). Only tests present in those runs count.',
    '- Engine: the test gets the `flaky` label from `scoreTests` (a commit with both a pass and a fail).',
    '- Baseline: Playwright marked the test flaky in any loaded run (`tests[*].status === "flaky"` in the raw JSON, that is, it failed and then passed on retry).',
    '- Precision or F1 shows n/a when it is undefined (nothing predicted).',
    '',
    '## Results',
    '',
    '| Method | Runs | Precision | Recall | F1 | TP | FP | FN |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...table,
    '',
    ...(tie
      ? [
          'The engine and the baseline score the same here: in this lab every flaky test also failed and then passed on a retry within one run, which is exactly what Playwright marks as flaky. The lab does not yet contain a test that is flaky only across runs of the same commit, so it cannot show where the engine adds to the baseline.',
          '',
        ]
      : []),
    '## Limits',
    '',
    'This is a synthetic lab with 9 tests, one browser (Chromium) and 12 runs over 6 commits, with causes we injected ourselves. It shows the engine gives the known answers; it is not a real-world benchmark. The check against public real-world data (spec section 11.1, item 5) is a v1 item, because that dataset needs the JUnit importer.',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const manifest: ManifestEntry[] = JSON.parse(readFileSync('fixtures/lab/manifest.json', 'utf8'));
  const labels: Record<string, string> = JSON.parse(readFileSync('flake-lab/labels.json', 'utf8'));
  mkdirSync('docs/eval', { recursive: true });
  writeFileSync('docs/eval/lab-detection.md', buildReport(evaluate(manifest, 'fixtures/lab', labels)));
  process.stdout.write('wrote docs/eval/lab-detection.md\n');
}
